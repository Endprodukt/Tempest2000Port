#!/usr/bin/env python3
"""make_rom_data.py - the release edition's data, which needs the player's ROM.

The full edition compiles Atari's data in (src/gen/t2k_data.c, assets/). The
release edition holds none of it. This writes src/gen/t2k_data_rom.c from
src/gen/t2k_data.c and the Tempest 2000 Jaguar ROM:

  - every table of numbers of t2k_data.c is left empty, and filled when the
    game starts from the player's ROM: what is shipped is the tables XORed
    with bytes of the ROM, nothing anyone can use without it;
  - for every sound effect and tune, where it lies in the ROM (they are in it
    as they are; the game reads them from there);
  - the ROM's size and CRC32, so a wrong or damaged ROM is refused.

    python tools/make_rom_data.py [rom]     (default: the source's orig/t2k.jag)
"""
import os
import re
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "reference", "tempest2k", "src")
FULL = os.path.join(ROOT, "src", "gen", "t2k_data.c")
OUT = os.path.join(ROOT, "src", "gen", "t2k_data_rom.c")
KEY_BASE = 0x100000             # where in the ROM the XOR key starts

TYPES = {"signed char": (1, "b"), "unsigned char": (1, "B"), "short": (2, "h"),
         "unsigned short": (2, "H"), "int": (4, "i")}
ARRAY = re.compile(r"^(static )?const (signed char|unsigned char|unsigned short|short|int) "
                   r"(\w+)\[(\d*)\] = \{([-0-9,\s]*)\};$")

# images_sounds.s: the tunes in the order of the game's tune table.
TUNES = ["tune13", "tune7", "tune1", "tune3", "rave4", "tune5", "tune12"]


def main():
    rom_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SRC, "..", "orig", "t2k.jag")
    rom = open(rom_path, "rb").read()
    crc = zlib.crc32(rom) & 0xFFFFFFFF

    blob = bytearray()
    fills = []
    out = ["/* Generated by tools/make_rom_data.py from src/gen/t2k_data.c and the ROM.",
           " * Do not edit: change the tools and run them again. Holds none of the",
           " * game's data: the tables below are filled from the player's ROM. */",
           '#include "t2k_data.h"', '#include "rom.h"', ""]
    for line in open(FULL, encoding="utf-8").read().split("\n"):
        m = ARRAY.match(line)
        if not m or line.startswith("/*"):
            if not line.startswith(("/* Generated", " * Do not edit", '#include "t2k_data.h"')):
                out.append(line)
            continue
        static, ctype, name, _, body = m.groups()
        values = [int(v) for v in body.split(",") if v.strip()]
        size, code = TYPES[ctype]
        for v in values:
            blob += int(v).to_bytes(size, "little", signed=code.islower())
        fills.append((name, size, len(values)))
        out.append(f"{static or ''}{ctype} {name}[{len(values)}];")

    key = bytes(rom[(KEY_BASE + i) % len(rom)] for i in range(len(blob)))
    mask = bytes(a ^ b for a, b in zip(blob, key))

    out.append("")
    out.append(f"static const unsigned char mask[{len(mask)}] = {{")
    for i in range(0, len(mask), 24):
        out.append("    " + ",".join(str(b) for b in mask[i:i + 24]) + ",")
    out.append("};")
    out.append("")
    out.append("static const struct { void *table; int size, count; } fill[] = {")
    for name, size, count in fills:
        out.append(f"    {{{name}, {size}, {count}}},")
    out.append("};")

    # The effects and tunes, where they lie in the ROM.
    table = open(os.path.join(SRC, "incbin", "sound_samples_table.bin"), "rb").read()
    effects = []
    for i in range(30):
        data = open(os.path.join(SRC, "sounds", "samples", "%02d" % (i + 1)), "rb").read()
        at = rom.find(data)
        effects.append((at, len(data)) if at >= 0 else (0, 0))  # 04 and 05 are not in the ROM
    tunes = []
    for t in TUNES:
        data = open(os.path.join(SRC, "sounds", t + ".mod"), "rb").read()
        at = rom.find(data)
        assert at >= 0, t
        tunes.append((at, len(data)))
    out.append("")
    out.append("const rom_place rom_effects[30] = {" + ",".join(f"{{{a},{n}}}" for a, n in effects) + "};")
    out.append("const rom_place rom_tunes[7] = {" + ",".join(f"{{{a},{n}}}" for a, n in tunes) + "};")
    out.append(f"const long rom_size = {len(rom)};")
    out.append(f"const unsigned long rom_crc = 0x{crc:08x}UL;")
    out.append("")
    out.append("void rom_fill_tables(const unsigned char *rom)")
    out.append("{")
    out.append("    long at = 0, i;")
    out.append("    int t;")
    out.append("    for (t = 0; t < (int)(sizeof fill / sizeof fill[0]); t++) {")
    out.append("        unsigned char *p = fill[t].table;")
    out.append("        for (i = 0; i < (long)fill[t].size * fill[t].count; i++, at++)")
    out.append(f"            p[i] = mask[at] ^ rom[({KEY_BASE}L + at) % rom_size];")
    out.append("    }")
    out.append("}")
    out.append("")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(out))
    print(f"{len(fills)} tables, {len(blob)} bytes, ROM crc {crc:08x} -> {OUT}")


if __name__ == "__main__":
    main()
